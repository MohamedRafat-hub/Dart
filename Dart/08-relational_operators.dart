void main() {
  int a = 10;
  int b = 20;

  // Equal to
  print(a == b); // false

  // Greater than
  print(a > b); // false

  // Less than
  print(a < b); // true

  // Greater than or equal to
  print(a >= b); // false

  // Less than or equal to
  print(a <= b); // true

  // Not equal to
  print(a != b); // true
}