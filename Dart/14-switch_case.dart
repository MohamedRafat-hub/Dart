void main() {
  int dayNumber = 2;

  switch (dayNumber) {
    case 1:
      print("Day is Saturday");
      break;

    case 2:
      print("Day is Sunday");
      break;

    case 3:
      print("Day is Monday");
      break;

    case 4:
      print("Day is Tuesday");
      break;

    case 5:
      print("Day is Wednesday");
      break;

    case 6:
      print("Day is Thursday");
      break;

    case 7:
      print("Day is Friday");
      break;

    default:
      print("Invalid day number. Please enter a number from 1 to 7.");
  }
}