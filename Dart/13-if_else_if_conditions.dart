void main() {
  int dayNumber = 2;

  if (dayNumber == 1) {
    print("Day is Saturday");
  } else if (dayNumber == 2) {
    print("Day is Sunday");
  } else if (dayNumber == 3) {
    print("Day is Monday");
  } else if (dayNumber == 4) {
    print("Day is Tuesday");
  } else if (dayNumber == 5) {
    print("Day is Wednesday");
  } else if (dayNumber == 6) {
    print("Day is Thursday");
  } else if (dayNumber == 7) {
    print("Day is Friday");
  } else {
    print("Invalid day number. Please enter a number from 1 to 7.");
  }
}